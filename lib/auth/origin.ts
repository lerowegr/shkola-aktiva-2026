/**
 * Откуда пришёл запрос, меняющий данные.
 *
 * Единственная защита сайта от подделки запросов с чужих сайтов —
 * это была кука `SameSite=lax`: браузер просто не прикладывал её к
 * запросам, начатым с другого домена. Telegram на компьютере показывает
 * Mini App внутри рамки на своей странице, и в таком окружении `lax`
 * куку не отдаёт — то есть человек видел бы экран входа.
 *
 * Куку пришлось ослабить до `none`, и защиту нужно вернуть в другом
 * месте. Здесь.
 *
 * Правило одно: если браузер сказал, откуда запрос, — этот адрес обязан
 * быть нашим. Браузеры прикладывают `Origin` ко всем POST-запросам, в том
 * числе к своим же; именно поэтому проверка работает. А если заголовка
 * нет вовсе — это не браузер (curl, проверка живости, скрипт на сервере),
 * и подделывать ему нечего: чужую куку он всё равно не получит.
 */
export function isTrustedOrigin(
  origin: string | undefined,
  allowedHosts: readonly (string | undefined)[],
): boolean {
  // Заголовка нет — запрос не из браузера. См. рассуждение выше.
  if (!origin) return true;

  // «null» присылают песочницы и страницы с data: — точно не мы.
  if (origin === "null") return false;

  let host: string;
  try {
    host = new URL(origin).host;
  } catch {
    // Невнятный заголовок разбирать не будем.
    return false;
  }

  return allowedHosts.some((allowed) => allowed && hostOf(allowed) === host);
}

/**
 * Из «https://sst-snimk.ru/» и из «sst-snimk.ru:3000» одинаково достаёт хост.
 *
 * Проверка на «://» обязательна, и вот почему. `new URL("localhost:3100")`
 * не падает: разборщик видит «localhost:» и считает это названием
 * протокола, а хост остаётся пустым. Голый хост с портом — обычный вид
 * заголовка Host, и без этой проверки он молча превращался в пустую
 * строку, то есть не совпадал ни с чем.
 */
function hostOf(value: string): string {
  if (!value.includes("://")) return value;

  try {
    return new URL(value).host;
  } catch {
    return value;
  }
}
